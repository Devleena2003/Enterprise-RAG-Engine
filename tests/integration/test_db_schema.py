import uuid

from sqlalchemy import text

from rag_engine.db.models import Document, DocumentChunk
from rag_engine.db.session import SessionLocal


def test_document_chunk_insert_tsvector_and_cascade_delete() -> None:
    db = SessionLocal()
    doc_id = uuid.uuid4()
    unique_hash = f"test_hash_{doc_id.hex}"

    try:
        doc = Document(
            id=doc_id,
            filename="sample_policy.pdf",
            file_hash=unique_hash,
            doc_type="insurance_policy",
            total_pages=5,
            status="ready",
            metadata_json={"jurisdiction": "US-NY"},
        )
        chunk = DocumentChunk(
            document_id=doc_id,
            chunk_index=0,
            page_number=2,
            page_end=2,
            section_title="Section 4.2 Deductible",
            content="Flood damage coverage requires a separate endorsement under Clause 14B.",
            token_count=12,
            char_count=71,
            chunk_type="text",
            embedding=[0.01] * 384,
        )
        doc.chunks.append(chunk)
        db.add(doc)
        db.commit()

        # 1. Verify full-text search_vector was generated by PostgreSQL automatically
        matched_id = db.execute(
            text(
                "SELECT id FROM document_chunks "
                "WHERE document_id = :doc_id "
                "AND search_vector @@ plainto_tsquery('english', 'Clause 14B deductible')"
            ),
            {"doc_id": doc_id},
        ).scalar()
        assert matched_id == chunk.id

        # 2. Verify pgvector cosine distance query works
        distance = db.execute(
            text(
                "SELECT embedding <=> CAST(:q AS vector) "
                "FROM document_chunks WHERE id = :cid"
            ),
            {"q": str([0.01] * 384), "cid": chunk.id},
        ).scalar()
        assert distance is not None and distance < 0.0001

        # 3. Verify CASCADE delete removes chunks when parent document is deleted
        db.delete(doc)
        db.commit()

        remaining = db.execute(
            text("SELECT count(*) FROM document_chunks WHERE document_id = :doc_id"),
            {"doc_id": doc_id},
        ).scalar()
        assert remaining == 0
    finally:
        # Defensive cleanup if assertion fails mid-test
        db.rollback()
        db.execute(text("DELETE FROM documents WHERE file_hash = :h"), {"h": unique_hash})
        db.commit()
        db.close()